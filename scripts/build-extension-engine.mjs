// Copies the compiled detection engine into the extension, so prompts are
// checked inside the browser with the same code the server runs. Run after
// `tsc`; `--check` fails when the committed copy has drifted from the build.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const modules = ['scanner.js', 'policy.js', 'credential-context.js'];
const target = new URL('../browser-extension/engine/', import.meta.url);
const check = process.argv.includes('--check');
const header = '// Generated by scripts/build-extension-engine.mjs from the TypeScript sources. Do not edit.\n';
mkdirSync(target, { recursive: true });
const stale = [];
for (const name of modules) {
  const built = header + readFileSync(new URL(`../dist/${name}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
  const path = new URL(name, target);
  if (check) {
    let current = '';
    try { current = readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch {}
    if (current !== built) stale.push(name);
  } else writeFileSync(path, built);
}
if (stale.length) {
  console.error(`Extension engine out of date: ${stale.join(', ')}. Run: npm run build:extension`);
  process.exit(1);
}
console.log(check ? 'Extension engine matches the compiled sources.' : `Extension engine updated: ${modules.join(', ')}`);
